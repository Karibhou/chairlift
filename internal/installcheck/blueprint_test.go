// blueprintDir holds every .blp source and the .ui XML compiled from it.
const blueprintDir = "internal/ui"

// generatedMarker is the header blueprint-compiler writes into every .ui.
const generatedMarker = "@generated by blueprint-compiler"

// uiObjects maps each id in one compiled blueprint to the GObject class it
// builds. A <menu> and an id'd <section> both build a GMenu.
func uiObjects(t *testing.T, path string) map[string]string {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v", path, err)
	}
	objects := map[string]string{}
	decoder := xml.NewDecoder(strings.NewReader(string(data)))
	for {
		tok, err := decoder.Token()
		if err != nil {
			break
		}
		start, ok := tok.(xml.StartElement)
		if !ok {
			continue
		}
		var id, class string
		for _, attr := range start.Attr {
			switch attr.Name.Local {
			case "id":
				id = attr.Value
			case "class":
				class = attr.Value
			}
		}
		if id == "" {
			continue
		}
		switch start.Name.Local {
		case "object":
			objects[id] = class
		case "menu", "section", "submenu":
			objects[id] = "GMenu"
		}
	}
	return objects
}

// blueprintBinding is one Go struct bound to a blueprint through ui.Bind.
type blueprintBinding struct {
	where  string
	file   string
	fields map[string]string // ui id -> expected class
	names  map[string]string // ui id -> Go field, for messages
}

// goClass names the GObject class a puregotk field type wraps:
// *adw.NavigationSplitView is AdwNavigationSplitView, *gtk.Button is
// GtkButton, *gio.Menu is GMenu.
func goClass(expr ast.Expr) (string, bool) {
	star, ok := expr.(*ast.StarExpr)
	if !ok {
		return "", false
	}
	sel, ok := star.X.(*ast.SelectorExpr)
	if !ok {
		return "", false
	}
	pkg, ok := sel.X.(*ast.Ident)
	if !ok {
		return "", false
	}
	switch pkg.Name {
	case "adw":
		return "Adw" + sel.Sel.Name, true
	case "gtk":
		return "Gtk" + sel.Sel.Name, true
	case "gio":
		return "G" + sel.Sel.Name, true
	}
	return "", false
}

func isUIFile(expr ast.Expr) bool {
	sel, ok := expr.(*ast.SelectorExpr)
	if !ok {
		return false
	}
	pkg, ok := sel.X.(*ast.Ident)
	return ok && pkg.Name == "ui" && sel.Sel.Name == "File"
}

func tagValue(field *ast.Field) string {
	if field.Tag == nil {
		return ""
	}
	raw, err := strconv.Unquote(field.Tag.Value)
	if err != nil {
		return ""
	}
	return reflect.StructTag(raw).Get("ui")
}

// blueprintBindings parses every non-test Go file under internal/ and cmd/
// for structs carrying a ui.File field, the shape ui.Bind requires.
func blueprintBindings(t *testing.T, root string) []blueprintBinding {
	t.Helper()
	var bindings []blueprintBinding
	for _, dir := range []string{"internal", "cmd"} {
		err := filepath.WalkDir(filepath.Join(root, dir), func(path string, d fs.DirEntry, err error) error {
			if err != nil || d.IsDir() || !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
				return err
			}
			file, err := parser.ParseFile(token.NewFileSet(), path, nil, parser.ParseComments)
			if err != nil {
				return err
			}
			rel, _ := filepath.Rel(root, path)
			ast.Inspect(file, func(n ast.Node) bool {
				spec, ok := n.(*ast.TypeSpec)
				if !ok {
					return true
				}
				st, ok := spec.Type.(*ast.StructType)
				if !ok {
					return true
				}
				binding := blueprintBinding{
					where:  rel + ":" + spec.Name.Name,
					fields: map[string]string{},
					names:  map[string]string{},
				}
				for _, field := range st.Fields.List {
					tag := tagValue(field)
					if tag == "" {
						continue
					}
					if isUIFile(field.Type) {
						binding.file = tag
						continue
					}
					class, ok := goClass(field.Type)
					if !ok {
						t.Errorf("%s: ui-tagged field of type %T is not a *adw/*gtk/*gio wrapper", binding.where, field.Type)
						continue
					}
					name := "_"
					if len(field.Names) > 0 {
						name = field.Names[0].Name
					}
					binding.fields[tag] = class
					binding.names[tag] = name
				}
				if binding.file != "" {
					bindings = append(bindings, binding)
				} else if len(binding.fields) > 0 {
					t.Errorf("%s has ui-tagged fields but no ui.File field naming its blueprint", binding.where)
				}
				return true
			})
			return nil
		})
		if err != nil {
			t.Fatalf("walk %s: %v", dir, err)
		}
	}
	return bindings
}

// TestBlueprintBindingsMatchTheirUI holds the Go side of every blueprint to
// the compiled XML without loading GTK: a binding struct names a blueprint
// that exists, each tagged field names an id the blueprint defines, and the
// field's wrapper type is the class the blueprint builds. ui.Bind would only
// discover a mismatch by panicking at startup, or worse, by handing a
// GtkButton pointer to code that calls it a GtkSwitch.
func TestBlueprintBindingsMatchTheirUI(t *testing.T) {
	root := RepoRoot()
	bindings := blueprintBindings(t, root)
	if len(bindings) == 0 {
		t.Fatal("found no ui.Bind binding structs; the scan is broken")
	}
	bound := map[string]bool{}
	for _, binding := range bindings {
		path := filepath.Join(root, blueprintDir, binding.file+".ui")
		if _, err := os.Stat(path); err != nil {
			t.Errorf("%s binds blueprint %q, but %s does not exist", binding.where, binding.file, path)
			continue
		}
		bound[binding.file] = true
		objects := uiObjects(t, path)
		ids := make([]string, 0, len(binding.fields))
		for id := range binding.fields {
			ids = append(ids, id)
		}
		sort.Strings(ids)
		for _, id := range ids {
			got, ok := objects[id]
			switch {
			case !ok:
				t.Errorf("%s.%s binds %q, which %s.blp does not define", binding.where, binding.names[id], id, binding.file)
			case got != binding.fields[id]:
				t.Errorf("%s.%s binds %q as %s, but %s.blp builds a %s", binding.where, binding.names[id], id, binding.fields[id], binding.file, got)
			}
		}
	}
	for _, name := range blueprintNames(t, root, ".ui") {
		if !bound[name] {
			t.Errorf("internal/ui/%s.ui is bound by no struct; delete the blueprint or bind it", name)
		}
	}
}

func blueprintNames(t *testing.T, root, ext string) []string {
	t.Helper()
	matches, err := filepath.Glob(filepath.Join(root, blueprintDir, "*"+ext))
	if err != nil {
		t.Fatal(err)
	}
	var names []string
	for _, m := range matches {
		names = append(names, strings.TrimSuffix(filepath.Base(m), ext))
	}
	return names
}

// TestEveryBlueprintIsCompiled pairs each .blp with the generated .ui the
// binary embeds. Whether the pair is current is checked by recompiling in
// the pinned Dakota image (scripts/blueprints.sh --check, a CI step); this
// test only needs the file system, so it also runs in `make ci` on any host.
func TestEveryBlueprintIsCompiled(t *testing.T) {
	root := RepoRoot()
	sources := blueprintNames(t, root, ".blp")
	if len(sources) == 0 {
		t.Fatal("no blueprints under internal/ui")
	}
	compiled := map[string]bool{}
	for _, name := range blueprintNames(t, root, ".ui") {
		compiled[name] = true
		data, err := os.ReadFile(filepath.Join(root, blueprintDir, name+".ui"))
		if err != nil {
			t.Fatal(err)
		}
		if !strings.Contains(string(data), generatedMarker) {
			t.Errorf("internal/ui/%s.ui is not blueprint-compiler output; edit %s.blp and run make blueprints", name, name)
		}
	}
	for _, name := range sources {
		if !compiled[name] {
			t.Errorf("internal/ui/%s.blp has no compiled %s.ui; run make blueprints", name, name)
		}
		delete(compiled, name)
	}
	for name := range compiled {
		t.Errorf("internal/ui/%s.ui has no %s.blp source", name, name)
	}
}

// TestBlueprintsDoNotSpellTheProductName keeps the display name's one owner:
// a blueprint literal would bypass internal/branding.AppName the same way a
// Go literal would, so the product name is set from Go after binding.
func TestBlueprintsDoNotSpellTheProductName(t *testing.T) {
	root := RepoRoot()
	for _, name := range blueprintNames(t, root, ".blp") {
		data, err := os.ReadFile(filepath.Join(root, blueprintDir, name+".blp"))
		if err != nil {
			t.Fatal(err)
		}
		if strings.Contains(string(data), branding.AppName) {
			t.Errorf("internal/ui/%s.blp spells %q; set it from branding.AppName in Go", name, branding.AppName)
		}
	}
}

// newerThanFloor lists the libadwaita classes introduced after 1.6, the
// oldest release ChairLift supports (Bluefin LTS). GtkBuilder aborts the
// process on a class the running library does not know, so a blueprint may
// use one only behind a runtime version check.
var newerThanFloor = map[string]string{
	"AdwToggleGroup":         "1.7",
	"AdwToggle":              "1.7",
	"AdwWrapBox":             "1.7",
	"AdwWrapLayout":          "1.7",
	"AdwInlineViewSwitcher":  "1.7",
	"AdwShortcutsDialog":     "1.8",
	"AdwShortcutsSection":    "1.8",
	"AdwShortcutsItem":       "1.8",
	"AdwShortcutLabel":       "1.8",
	"AdwSidebar":             "1.9",
	"AdwSidebarItem":         "1.9",
	"AdwSidebarSection":      "1.9",
	"AdwViewSwitcherSidebar": "1.9",
}

// versionGatedBlueprints are bound only after a runtime version check, each
// with a fallback blueprint for older libadwaita.
var versionGatedBlueprints = map[string]string{
	"shortcuts": "ui.SupportsShortcutsDialog; shortcuts-legacy is the fallback",
}

// TestBlueprintsStayWithinTheLibadwaitaFloor keeps every blueprint loadable
// on the oldest supported libadwaita unless it is version gated.
func TestBlueprintsStayWithinTheLibadwaitaFloor(t *testing.T) {
	root := RepoRoot()
	for _, name := range blueprintNames(t, root, ".ui") {
		if _, gated := versionGatedBlueprints[name]; gated {
			continue
		}
		data, err := os.ReadFile(filepath.Join(root, blueprintDir, name+".ui"))
		if err != nil {
			t.Fatal(err)
		}
		for class, since := range newerThanFloor {
			if strings.Contains(string(data), `class="`+class+`"`) {
				t.Errorf("internal/ui/%s.blp uses %s (libadwaita %s), newer than the 1.6 floor; gate it like shortcuts.blp", name, class, since)
			}
		}
	}
	for name := range versionGatedBlueprints {
		if _, err := os.Stat(filepath.Join(root, blueprintDir, name+".blp")); err != nil {
			t.Errorf("versionGatedBlueprints names %q, which does not exist", name)
		}
	}
}

// blueprintAction matches an action a blueprint names: a widget's
// action-name property or a menu item's action attribute.
var blueprintAction = regexp.MustCompile(`<(?:property|attribute) name="action(?:-name)?"[^>]*>([^<]+)<`)

// TestBlueprintActionsAreRegistered holds every action a blueprint names to
// a registration in its owner, the way TestEveryAdvertisedActionIsRegistered
// holds the shortcut tables: GTK silently ignores an action nobody added, so
// a renamed action would leave a menu item or button that does nothing.
func TestBlueprintActionsAreRegistered(t *testing.T) {
	root := RepoRoot()
	owners := map[string]string{
		"win.": filepath.Join(root, "internal", "window", "window.go"),
		"app.": filepath.Join(root, "internal", "app", "app.go"),
	}
	for _, name := range blueprintNames(t, root, ".ui") {
		data, err := os.ReadFile(filepath.Join(root, blueprintDir, name+".ui"))
		if err != nil {
			t.Fatal(err)
		}
		for _, match := range blueprintAction.FindAllStringSubmatch(string(data), -1) {
			action := match[1]
			scope := action[:strings.Index(action, ".")+1]
			owner, ok := owners[scope]
			if !ok {
				t.Errorf("internal/ui/%s.blp names %q, outside the win. and app. scopes", name, action)
				continue
			}
			source, err := os.ReadFile(owner)
			if err != nil {
				t.Fatal(err)
			}
			if !strings.Contains(string(source), `gio.NewSimpleAction("`+strings.TrimPrefix(action, scope)+`"`) {
				t.Errorf("internal/ui/%s.blp names %q, which %s never registers", name, action, owner)
			}
		}
	}
}
